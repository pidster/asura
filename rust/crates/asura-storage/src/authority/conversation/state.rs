/// Rebuilds the projection of a tool call from its frames: the kind 14,
/// the record that follows it ([`ToolRecord::follow_frame`]: kind 26 or a
/// kind 30 model note), when known, and its result (kind 15 or kind 29).
pub fn tool_from_frames(
    installation: Id,
    binding: [Id; 3],
    project: Id,
    intent: (Locator, Record),
    follow: Option<(Locator, Record)>,
    result: Option<(Locator, Record)>,
) -> Result<ToolRecord> {
    let Record::ToolCall(call) = intent.1 else {
        return Err(ReplayError::Corrupt);
    };
    let run = call.decision == ToolDecision::Run;
    let create = (run && call.tool_operation == Some(ToolOperation::CreateNote))
        .then(|| {
            CreateNoteCall::derive(
                binding,
                project,
                call.operation,
                call.generation,
                call.ordinal,
            )
        })
        .transpose()?;
    let mut exec = (run && call.tool_operation == Some(ToolOperation::ExecCmd))
        .then(|| exec_cmd_call(installation, &call, intent.0.sequence));
    let origin = JobOrigin::Model {
        operation: call.operation,
        generation: call.generation,
        ordinal: call.ordinal,
    };
    let reference = RetentionAuthor::Model {
        operation: call.operation,
        generation: call.generation,
        ordinal: call.ordinal,
    };
    let mut note = None;
    match follow {
        None => {}
        Some((frame, Record::JobIntent(p))) if p.origin == origin => {
            exec.as_deref_mut().ok_or(ReplayError::Corrupt)?.job_intent = Some(frame);
        }
        Some((frame, Record::JobRetention(p)))
            if run
                && call.tool_operation == Some(ToolOperation::JobNote)
                && p.author == reference =>
        {
            note = Some((p.job, frame));
        }
        Some(_) => return Err(ReplayError::Corrupt),
    }
    let operation = call.tool_operation;
    let mut tool = tool_record(*call, intent.0, create, exec);
    tool.note = note;
    match result {
        None => {}
        Some((frame, Record::ToolResult(p))) => {
            let operation = operation.ok_or(ReplayError::Corrupt)?;
            require(run && !operation.job_result())?;
            tool.result_frame = Some(frame);
            apply_result_projection(&mut tool, operation, &p);
        }
        Some((frame, Record::JobResult(p))) => {
            require(run && operation.is_some_and(ToolOperation::job_result))?;
            tool.result_frame = Some(frame);
            tool.result_status = Some(p.status);
            tool.job_result = Some(p);
        }
        Some(_) => return Err(ReplayError::Corrupt),
    }
    Ok(tool)
}

/// Frames of one contiguous journal in memory, as segment 1, with no runs.
/// Used by the pure replay and by tests.
pub struct MemoryIndex<'a> {
    pub segments: BTreeMap<u64, &'a [u8]>,
}
impl<'a> MemoryIndex<'a> {
    /// The located frame bytes.
    fn bytes(&self, locator: &Locator) -> Result<&'a [u8]> {
        let bytes: &'a [u8] = self
            .segments
            .get(&locator.segment)
            .ok_or(ReplayError::Corrupt)?;
        let start = locator.offset as usize;
        bytes
            .get(start..start + locator.length as usize)
            .ok_or(ReplayError::Corrupt)
    }
}
impl Index for MemoryIndex<'_> {
    fn get(&mut self, _: &Key) -> Result<Option<Value>> {
        Ok(None)
    }
    fn range(&mut self, _: &Key, _: &Key, _: bool, _: usize) -> Result<Vec<(Key, Value)>> {
        Ok(Vec::new())
    }
    fn frame(&mut self, locator: &Locator) -> Result<Record> {
        authority::verified_record(self.bytes(locator)?, locator)
    }
    fn frame_owner(&mut self, locator: &Locator) -> Result<(u64, Record)> {
        let (context, record, _) = authority::verified_frame(self.bytes(locator)?, locator)?;
        Ok((context.owner_generation, record))
    }
}

/// Strict all-or-nothing replay of one contiguous journal held in memory, as
/// segment file 1. Offsets in the returned locators refer only to the input.
pub fn replay(bytes: &[u8], cancelled: &AtomicBool) -> Result<Replay> {
    authority::active(cancelled)?;
    if bytes.is_empty() {
        return Err(ReplayError::Empty);
    }
    let mut index = MemoryIndex {
        segments: BTreeMap::from([(1, bytes)]),
    };
    let mut state: Option<Replay> = None;
    let mut offset = 0;
    while offset < bytes.len() {
        authority::active(cancelled)?;
        let envelope = authority::envelope(&bytes[offset..])?;
        let locator = Locator {
            sequence: envelope.context.sequence,
            segment: 1,
            offset: u32::try_from(offset).map_err(|_| ReplayError::Limit)?,
            length: envelope.length as u32,
        };
        let record = decode_record(envelope.kind, envelope.payload)?;
        state = Some(apply_next(
            state,
            &envelope.context,
            record,
            envelope.digest,
            locator,
            &mut index,
        )?);
        offset += envelope.length;
    }
    authority::active(cancelled)?;
    state.ok_or(ReplayError::Empty)
}
/// Applies one frame to the state, or starts the state at kind 10.
pub fn apply_next(
    state: Option<Replay>,
    context: &FrameContext,
    record: Record,
    digest: Hash,
    frame: Locator,
    index: &mut dyn Index,
) -> Result<Replay> {
    match state {
        Some(mut s) => {
            s.apply_frame(context, record, digest, frame, index)?;
            Ok(s)
        }
        None => {
            let Record::PendingInit(p) = record else {
                return Err(ReplayError::Corrupt);
            };
            let mut s = Replay::genesis(context, p, frame)?;
            s.sequence = context.sequence;
            s.revision = next(context.expected_revision)?;
            s.last_digest = digest;
            s.last_frame = frame;
            s.reserve()?;
            Ok(s)
        }
    }
}
